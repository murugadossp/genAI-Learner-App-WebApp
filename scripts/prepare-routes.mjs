import {
  writeFileSync,
  mkdirSync,
  existsSync,
  readdirSync,
  unlinkSync,
} from "node:fs";
import { lessons, production } from "./lesson-registry.mjs";
import { chapterRoutes } from "./chapters.mjs";
const marker = "// Generated by prepare-routes; do not edit.\n";
const root = "app/learn";
if (existsSync(root))
  for (const module of readdirSync(root, { withFileTypes: true }).filter((x) =>
    x.isDirectory(),
  ))
    for (const lesson of readdirSync(`${root}/${module.name}`, {
      withFileTypes: true,
    }).filter((x) => x.isDirectory())) {
      const path = `${root}/${module.name}/${lesson.name}/page.tsx`;
      if (
        existsSync(path) &&
        (await import("node:fs")).readFileSync(path, "utf8").startsWith(marker)
      )
        unlinkSync(path);
    }
const courseRoot = "app/course";
if (existsSync(courseRoot))
  for (const dir of readdirSync(courseRoot, { withFileTypes: true }).filter(
    (x) => x.isDirectory() && x.name.startsWith("chapter-"),
  )) {
    const path = `${courseRoot}/${dir.name}/page.tsx`;
    if (
      existsSync(path) &&
      (await import("node:fs")).readFileSync(path, "utf8").startsWith(marker)
    )
      unlinkSync(path);
  }
const routes = [
  ["app/page.tsx", "../src/studio/Landing", true],
  ["app/studio/page.tsx", "../../src/studio/Studio", true],
  ["app/course/page.tsx", "../../src/studio/Course", true],
  // One course page per chapter that has web lessons. Public once the chapter
  // has a published lesson; the page itself is built from the curriculum.
  ...chapterRoutes().map((chapter) => [
    chapter.path,
    "../../../src/studio/ChapterPage",
    chapter.published,
    `import ChapterPage from "../../../src/studio/ChapterPage";\nexport default function Page(){return <ChapterPage chapterId={${JSON.stringify(chapter.id)}} module=${JSON.stringify(chapter.module)} />}\n`,
  ]),
  ...lessons().map((meta) => [
    `app/learn/${meta.module}/${meta.lessonId}/page.tsx`,
    `../../../../src/lessons/${meta.module}/${meta.lessonId}/Lesson`,
    meta.webStatus === "published",
  ]),
];
for (const [path, target, published, source] of routes) {
  mkdirSync(path.slice(0, path.lastIndexOf("/")), { recursive: true });
  const notFoundPage =
    'import { notFound } from "next/navigation";\nexport default function Page(){notFound()}\n';
  writeFileSync(
    path,
    marker +
      (production && !published
        ? notFoundPage
        : (source ?? `export { default } from "${target}";\n`)),
  );
}
