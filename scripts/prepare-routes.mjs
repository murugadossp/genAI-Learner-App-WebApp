import {
  writeFileSync,
  mkdirSync,
  existsSync,
  readdirSync,
  unlinkSync,
} from "node:fs";
import { lessons, production } from "./lesson-registry.mjs";
const marker = "// Generated by prepare-routes; do not edit.\n";
const root = "app/learn";
if (existsSync(root))
  for (const module of readdirSync(root, { withFileTypes: true }).filter((x) =>
    x.isDirectory(),
  ))
    for (const lesson of readdirSync(`${root}/${module.name}`, {
      withFileTypes: true,
    }).filter((x) => x.isDirectory())) {
      const path = `${root}/${module.name}/${lesson.name}/page.tsx`;
      if (
        existsSync(path) &&
        (await import("node:fs")).readFileSync(path, "utf8").startsWith(marker)
      )
        unlinkSync(path);
    }
const routes = [
  ["app/page.tsx", "../src/studio/Landing", true],
  ["app/studio/page.tsx", "../../src/studio/Studio", true],
  ["app/course/page.tsx", "../../src/studio/Course", true],
  ["app/course/chapter-1/page.tsx", "../../../src/studio/CourseChapter1", true],
  [
    "app/course/chapter-p1/page.tsx",
    "../../../src/studio/CourseChapterP1",
    // Published once the module has a published lesson.
    lessons().some(
      (meta) =>
        meta.module === "python-for-ai" && meta.webStatus === "published",
    ),
  ],
  [
    "app/course/chapter-9/page.tsx",
    "../../../src/studio/CourseChapter9",
    // Published once a Chapter 9 lesson in genai-basics is published.
    lessons().some(
      (meta) =>
        meta.module === "genai-basics" &&
        meta.lessonId.startsWith("c9-") &&
        meta.webStatus === "published",
    ),
  ],
  ...lessons().map((meta) => [
    `app/learn/${meta.module}/${meta.lessonId}/page.tsx`,
    `../../../../src/lessons/${meta.module}/${meta.lessonId}/Lesson`,
    meta.webStatus === "published",
  ]),
];
for (const [path, target, published] of routes) {
  mkdirSync(path.slice(0, path.lastIndexOf("/")), { recursive: true });
  const safe =
    path === "app/page.tsx"
      ? "export default function Home(){return <main><h1>GenAI Learner</h1><p>Our web learning experience is coming soon.</p></main>}\n"
      : 'import { notFound } from "next/navigation";\nexport default function Page(){notFound()}\n';
  writeFileSync(
    path,
    marker +
      (production && !published
        ? safe
        : `export { default } from "${target}";\n`),
  );
}
