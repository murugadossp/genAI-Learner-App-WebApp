"use client";
import { useState } from "react";
import styles from "./lesson.module.css";

type Mode = "single" | "staged";
type Stage = 1 | 2 | 3;
type GateChoice = "unchecked" | "fixed" | "skipped";

export function StagePlannerLab() {
  const [mode, setMode] = useState<Mode>("single");
  const [showSlips, setShowSlips] = useState(false);
  const [stage, setStage] = useState<Stage>(1);
  const [gateChoice, setGateChoice] = useState<GateChoice>("unchecked");
  const [status, setStatus] = useState(
    "Showing the single big prompt view. Toggle mistakes or switch to the 3-stage plan.",
  );

  function switchMode(next: Mode) {
    setMode(next);
    if (next === "single") {
      setStatus(
        "Switched to Single big prompt mode. Inspect the long reply for buried rule breaks.",
      );
    } else {
      setStatus(
        "Switched to 3-stage plan mode. Start at Stage 1: Extract facts.",
      );
    }
  }

  function selectStage(next: Stage) {
    setStage(next);
    const labels: Record<Stage, string> = {
      1: "Viewing Stage 1: Extract availability and limits.",
      2: "Viewing Stage 2: Match roles to rules. Check the draft at the stage gate.",
      3:
        gateChoice === "fixed"
          ? "Viewing Stage 3: Draft email built from the checked schedule."
          : gateChoice === "skipped"
            ? "Viewing Stage 3: Draft email with unchecked Stage 2 errors carried over."
            : "Viewing Stage 3: Draft email. Notice how unchecked Stage 2 slips carry through.",
    };
    setStatus(labels[next]);
  }

  function handleReset() {
    setMode("single");
    setShowSlips(false);
    setStage(1);
    setGateChoice("unchecked");
    setStatus("Lab reset to Single big prompt mode.");
  }

  return (
    <div
      className={styles.lab}
      role="region"
      aria-label="Book Swap Stage Planner Lab"
    >
      <div className={styles.labHeader}>
        <div className={styles.modeGroup} role="group" aria-label="Prompt mode">
          <button
            type="button"
            className={`${styles.modeBtn} ${mode === "single" ? styles.modeBtnActive : ""}`}
            aria-pressed={mode === "single"}
            onClick={() => switchMode("single")}
          >
            Single big prompt
          </button>
          <button
            type="button"
            className={`${styles.modeBtn} ${mode === "staged" ? styles.modeBtnActive : ""}`}
            aria-pressed={mode === "staged"}
            onClick={() => switchMode("staged")}
          >
            3-stage plan
          </button>
        </div>
        <button type="button" className={styles.resetBtn} onClick={handleReset}>
          Reset
        </button>
      </div>

      <p className={styles.disclosure}>
        Simulated example: these prompts and replies are pre-written to show how
        staged checking works, not generated by a live AI model.
      </p>

      {mode === "single" ? (
        <div>
          <div className={styles.panelCard}>
            <div className={styles.panelLabel}>One-shot prompt</div>
            <p className={styles.promptQuote}>
              “Read my Book Swap volunteer notes, assign everyone to shifts,
              explain your reasoning, and write a friendly email under 80
              words.”
            </p>
          </div>

          <div className={styles.panelCard}>
            <div className={styles.panelLabel}>
              Simulated reply (sounds smooth, breaks Rules 1–4)
            </div>
            <p className={styles.replyText}>
              Here is a balanced schedule built around your team’s strengths.{" "}
              <span className={showSlips ? styles.slipHighlight : undefined}>
                Lina brings great energy to the morning sorting table
              </span>
              , while{" "}
              <span className={showSlips ? styles.slipHighlight : undefined}>
                Omar can handle the morning heavy boxes
              </span>{" "}
              since he is free all day.{" "}
              <span className={showSlips ? styles.slipHighlight : undefined}>
                Ben can greet afternoon visitors
              </span>
              , and{" "}
              <span className={showSlips ? styles.slipHighlight : undefined}>
                Tessa can cover afternoon pickup
              </span>
              . <strong>Draft email (86 words):</strong>{" "}
              <span className={showSlips ? styles.slipHighlight : undefined}>
                Hi everyone! Thank you so much for volunteering for Saturday’s
                neighborhood Book Swap—we truly could not run this wonderful
                community event without your generous help, enthusiasm, and
                dedication to local reading. Please arrive at least fifteen
                minutes before your shift starts so we can review the tables,
                signs, and book carts together before visitors begin arriving at
                the library lawn. Your assigned shifts are: Lina (morning book
                sorting), Omar (morning heavy boxes), Ben (afternoon welcome
                table), and Tessa (afternoon book pickup). Please reply today to
                confirm!
              </span>
            </p>
            <button
              type="button"
              className={styles.actionBtn}
              aria-pressed={showSlips}
              onClick={() => {
                const next = !showSlips;
                setShowSlips(next);
                setStatus(
                  next
                    ? "Highlighted broken rules (Rules 1–4) hidden inside the fluent single-pass reply."
                    : "Hid mistake highlights.",
                );
              }}
            >
              {showSlips ? "Hide mistake highlights" : "Reveal buried mistakes"}
            </button>

            {showSlips && (
              <ul className={styles.slipList}>
                <li>
                  <strong>Rule 1 broken:</strong> Lina is free in the afternoon
                  only (not morning), and Ben is free in the morning only (not
                  afternoon).
                </li>
                <li>
                  <strong>Rule 2 broken:</strong> Omar cannot lift heavy boxes.
                </li>
                <li>
                  <strong>Rule 3 broken:</strong> Tessa does not have a car for
                  book pickup.
                </li>
                <li>
                  <strong>Rule 4 broken:</strong> The email body is 86 words,
                  over the 80-word limit.
                </li>
              </ul>
            )}
          </div>
        </div>
      ) : (
        <div>
          <div
            className={styles.stageBar}
            role="group"
            aria-label="Workflow stages"
          >
            <button
              type="button"
              className={`${styles.stageTab} ${stage === 1 ? styles.stageTabActive : ""}`}
              aria-pressed={stage === 1}
              onClick={() => selectStage(1)}
            >
              1. Extract facts
            </button>
            <button
              type="button"
              className={`${styles.stageTab} ${stage === 2 ? styles.stageTabActive : ""}`}
              aria-pressed={stage === 2}
              onClick={() => selectStage(2)}
            >
              2. Match roles
            </button>
            <button
              type="button"
              className={`${styles.stageTab} ${stage === 3 ? styles.stageTabActive : ""}`}
              aria-pressed={stage === 3}
              onClick={() => selectStage(3)}
            >
              3. Draft email
            </button>
          </div>

          {stage === 1 && (
            <div className={styles.panelCard}>
              <div className={styles.panelLabel}>Stage 1 prompt</div>
              <p className={styles.promptQuote}>
                “List each volunteer’s free shift, available roles, and hard
                limits from my notes. Do not assign roles yet.”
              </p>
              <div className={styles.gateBox}>
                <div className={styles.panelLabel}>
                  Stage 1 output (easy to check in 10 seconds)
                </div>
                <ul className={styles.stageList}>
                  <li>
                    <strong>Ben:</strong> Morning only; cleared for heavy boxes;
                    no car.
                  </li>
                  <li>
                    <strong>Lina:</strong> Afternoon only; available for welcome
                    table; no heavy boxes; no car.
                  </li>
                  <li>
                    <strong>Omar:</strong> All day; has a car for book pickup;
                    cannot lift heavy boxes.
                  </li>
                  <li>
                    <strong>Tessa:</strong> Morning only; available for sorting
                    books by age group; no heavy boxes; no car.
                  </li>
                </ul>
                <div className={styles.gateActions}>
                  <button
                    type="button"
                    className="button small"
                    onClick={() => selectStage(2)}
                  >
                    Verified against notes → Go to Stage 2
                  </button>
                </div>
              </div>
            </div>
          )}

          {stage === 2 && (
            <div className={styles.panelCard}>
              <div className={styles.panelLabel}>Stage 2 prompt</div>
              <p className={styles.promptQuote}>
                “Using the checked list and Rules 1–3, assign one role per
                volunteer. Output only the 4 assignments.”
              </p>
              <div className={styles.gateBox}>
                <div className={styles.panelLabel}>
                  Stage 2 draft output (before your stage gate check)
                </div>
                {gateChoice === "fixed" ? (
                  <>
                    <span className={styles.badgeGood}>
                      ✓ Stage gate passed — slips fixed
                    </span>
                    <ul className={styles.stageList}>
                      <li>
                        <strong>Morning heavy boxes:</strong> Ben
                      </li>
                      <li>
                        <strong>Morning book sorting:</strong> Tessa
                      </li>
                      <li>
                        <strong>Afternoon welcome table:</strong> Lina
                      </li>
                      <li>
                        <strong>Afternoon book pickup:</strong> Omar
                      </li>
                    </ul>
                  </>
                ) : (
                  <>
                    <span className={styles.badgeWarn}>
                      ! Unchecked draft — spot the 4 assignment slips
                    </span>
                    <ul className={styles.stageList}>
                      <li>
                        <strong>Morning heavy boxes:</strong>{" "}
                        <span className={styles.slipHighlight}>Omar</span>{" "}
                        (cannot lift heavy boxes)
                      </li>
                      <li>
                        <strong>Morning book sorting:</strong>{" "}
                        <span className={styles.slipHighlight}>Lina</span>{" "}
                        (afternoon only)
                      </li>
                      <li>
                        <strong>Afternoon welcome table:</strong>{" "}
                        <span className={styles.slipHighlight}>Ben</span>{" "}
                        (morning only)
                      </li>
                      <li>
                        <strong>Afternoon book pickup:</strong>{" "}
                        <span className={styles.slipHighlight}>Tessa</span> (no
                        car)
                      </li>
                    </ul>
                  </>
                )}

                <div className={styles.gateActions}>
                  <button
                    type="button"
                    className="button small"
                    onClick={() => {
                      setGateChoice("fixed");
                      setStage(3);
                      setStatus(
                        "Stage 2 slips fixed at the stage gate. Moving to Stage 3 with the verified schedule.",
                      );
                    }}
                  >
                    Check &amp; fix slips → Stage 3
                  </button>
                  <button
                    type="button"
                    className={styles.actionBtn}
                    onClick={() => {
                      setGateChoice("skipped");
                      setStage(3);
                      setStatus(
                        "Skipped Stage 2 check. Watch how the wrong shifts carry into Stage 3.",
                      );
                    }}
                  >
                    Skip check → Stage 3
                  </button>
                </div>
              </div>
            </div>
          )}

          {stage === 3 && (
            <div className={styles.panelCard}>
              <div className={styles.panelLabel}>Stage 3 prompt</div>
              <p className={styles.promptQuote}>
                “Write a volunteer email under 80 words using only this schedule
                from Stage 2.”
              </p>
              <div className={styles.gateBox}>
                {gateChoice === "fixed" ? (
                  <>
                    <span className={styles.badgeGood}>
                      ✓ Clean email (43 words) — all 4 rules met
                    </span>
                    <p className={styles.replyText}>
                      Hi team! Here are your Saturday Book Swap shifts: Ben —
                      Morning heavy boxes; Tessa — Morning book sorting; Lina —
                      Afternoon welcome table; Omar — Afternoon book pickup.
                      Please reply to confirm, and thank you for helping our
                      neighborhood swap run smoothly!
                    </p>
                  </>
                ) : (
                  <>
                    <span className={styles.badgeWarn}>
                      ! Errors carried over from Stage 2 (38 words)
                    </span>
                    <p className={styles.replyText}>
                      Hi team! Here are your Saturday Book Swap shifts:{" "}
                      <span className={styles.slipHighlight}>
                        Omar — Morning heavy boxes
                      </span>
                      ;{" "}
                      <span className={styles.slipHighlight}>
                        Lina — Morning book sorting
                      </span>
                      ;{" "}
                      <span className={styles.slipHighlight}>
                        Ben — Afternoon welcome table
                      </span>
                      ;{" "}
                      <span className={styles.slipHighlight}>
                        Tessa — Afternoon book pickup
                      </span>
                      . Please reply to confirm, and thank you for helping!
                    </p>
                    <p className={styles.disclosure}>
                      Stage 3 obeyed the 80-word rule, but skipping the Stage 2
                      gate let wrong shifts flow straight into the email.
                    </p>
                    <div className={styles.gateActions}>
                      <button
                        type="button"
                        className="button small"
                        onClick={() => selectStage(2)}
                      >
                        Go back to Stage 2 gate
                      </button>
                    </div>
                  </>
                )}
              </div>
            </div>
          )}
        </div>
      )}

      <p className={styles.liveStatus} role="status" aria-live="polite">
        {status}
      </p>
    </div>
  );
}
